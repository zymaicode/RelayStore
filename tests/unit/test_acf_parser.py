"""Unit tests for the appmanifest (.acf / VDF) parser (M1-T01).

Written before the implementation on purpose: run red, then implement.
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src" / "py"))

from steam_research.model import AppRecord  # noqa: E402
from steam_research.parsers import (  # noqa: E402
    AcfAppState,
    AcfParseError,
    parse_acf,
    parse_acf_file,
)

FIXTURES = ROOT / "tests" / "fixtures" / "acf"
L4D2 = FIXTURES / "appmanifest_550.sample.acf"
GTA5 = FIXTURES / "appmanifest_3240220.sample.acf"
EMPTY = FIXTURES / "appmanifest_228980.sample.acf"
UNCLOSED = FIXTURES / "malformed_unclosed.acf"
BAD_TOKEN = FIXTURES / "malformed_bad_token.acf"
UNTERMINATED = FIXTURES / "malformed_unterminated_string.acf"


class FixtureParsingTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.l4d2 = parse_acf_file(L4D2)
        cls.gta = parse_acf_file(GTA5)
        cls.empty = parse_acf_file(EMPTY)

    def test_returns_state_object(self):
        self.assertIsInstance(self.l4d2, AcfAppState)

    def test_appid_and_name(self):
        self.assertEqual(self.l4d2.appid, 550)
        self.assertEqual(self.l4d2.name, "Left 4 Dead 2")

    def test_install_fields(self):
        self.assertEqual(self.l4d2.installdir, "Left 4 Dead 2")
        self.assertEqual(self.l4d2.buildid, "23990068")
        self.assertEqual(self.l4d2.state_flags, 4)
        self.assertEqual(self.l4d2.size_on_disk, 14964354280)

    def test_depots_keep_file_order(self):
        self.assertEqual([d.depot_id for d in self.l4d2.depots], [551, 552])

    def test_known_depot_values(self):
        depot = self.l4d2.depots[0]
        self.assertEqual(depot.depot_id, 551)
        self.assertEqual(depot.manifest_gid, "314878501352141828")
        self.assertEqual(depot.size, 11329675570)

    def test_depot_raw_fields_are_kept(self):
        self.assertEqual(self.l4d2.depots[0].raw["size"], "11329675570")

    def test_empty_installed_depots(self):
        self.assertEqual(self.empty.appid, 228980)
        self.assertEqual(self.empty.depots, ())
        self.assertEqual(self.empty.to_app_record().manifests, ())

    def test_gta_has_six_depots_including_shared(self):
        ids = [d.depot_id for d in self.gta.depots]
        self.assertEqual(len(ids), 6)
        self.assertIn(1899671, ids)
        self.assertIn(3240221, ids)

    def test_raw_appstate_dict_is_preserved(self):
        self.assertEqual(self.l4d2.raw["SizeOnDisk"], "14964354280")
        self.assertEqual(self.l4d2.raw["Universe"], "1")

    def test_to_app_record(self):
        rec = self.l4d2.to_app_record()
        self.assertIsInstance(rec, AppRecord)
        self.assertEqual(rec.appid, 550)
        self.assertEqual(rec.name, "Left 4 Dead 2")
        self.assertEqual(rec.depots, (551, 552))
        self.assertEqual(len(rec.manifests), 2)
        ref = rec.manifest_for(551)
        self.assertEqual(ref.gid, "314878501352141828")
        self.assertEqual(ref.size, 11329675570)
        self.assertEqual(ref.source, "acf")
        self.assertEqual(ref.appid, 550)
        self.assertTrue(ref.fetched_at.endswith("+00:00"), ref.fetched_at)

    def test_to_app_record_source_url_is_path(self):
        ref = self.l4d2.to_app_record().manifests[0]
        self.assertIn("appmanifest_550.sample.acf", ref.source_url)

    def test_to_app_record_manifests_sorted_by_depot(self):
        rec = self.gta.to_app_record()
        self.assertEqual(list(rec.depots), sorted(rec.depots))
        self.assertEqual([r.depot_id for r in rec.manifests], sorted(rec.depots))


class TextParsingTest(unittest.TestCase):
    def test_comments_bom_and_crlf(self):
        text = (
            "\ufeff// generated by steam, do not edit\r\n"
            '"AppState"\r\n'
            "{\r\n"
            '\t"appid"\t\t"42"  // inline comment\r\n'
            '\t"name"\t\t"Test App"\r\n'
            "}\r\n"
        )
        state = parse_acf(text)
        self.assertEqual(state.appid, 42)
        self.assertEqual(state.name, "Test App")

    def test_block_comments(self):
        text = '"AppState"\n{\n/* block\ncomment */\n"appid" "7"\n}\n'
        self.assertEqual(parse_acf(text).appid, 7)

    def test_keys_are_case_insensitive(self):
        text = '"AppState"\n{\n"APPID" "9"\n"NAME" "Case"\n}\n'
        state = parse_acf(text)
        self.assertEqual(state.appid, 9)
        self.assertEqual(state.name, "Case")

    def test_unquoted_values_are_accepted(self):
        text = '"AppState"\n{\n"appid" 11\n}\n'
        self.assertEqual(parse_acf(text).appid, 11)

    def test_escaped_quote_in_string(self):
        text = '"AppState"\n{\n"appid" "1"\n"name" "Say \\"hi\\""\n}\n'
        self.assertEqual(parse_acf(text).name, 'Say "hi"')

    def test_missing_name_is_none(self):
        self.assertIsNone(parse_acf('"AppState"\n{\n"appid" "1"\n}\n').name)


class ErrorReportingTest(unittest.TestCase):
    def test_unclosed_block_reports_opening_line(self):
        with self.assertRaises(AcfParseError) as ctx:
            parse_acf_file(UNCLOSED)
        self.assertEqual(ctx.exception.line, 2)
        self.assertIn("line 2", str(ctx.exception))

    def test_bad_token_reports_line(self):
        with self.assertRaises(AcfParseError) as ctx:
            parse_acf_file(BAD_TOKEN)
        self.assertEqual(ctx.exception.line, 4)
        self.assertIn("line 4", str(ctx.exception))

    def test_unterminated_string_reports_line(self):
        with self.assertRaises(AcfParseError) as ctx:
            parse_acf_file(UNTERMINATED)
        self.assertEqual(ctx.exception.line, 4)

    def test_empty_input(self):
        with self.assertRaises(AcfParseError) as ctx:
            parse_acf("   \n\n")
        self.assertEqual(ctx.exception.line, 3)

    def test_root_must_be_appstate(self):
        with self.assertRaises(AcfParseError) as ctx:
            parse_acf('"Other"\n{\n}\n')
        self.assertEqual(ctx.exception.line, 1)

    def test_missing_appid(self):
        with self.assertRaises(AcfParseError) as ctx:
            parse_acf('"AppState"\n{\n"name" "x"\n}\n')
        self.assertIn("appid", str(ctx.exception).lower())

    def test_non_numeric_appid(self):
        with self.assertRaises(AcfParseError) as ctx:
            parse_acf('"AppState"\n{\n"appid" "abc"\n}\n')
        self.assertEqual(ctx.exception.line, 3)

    def test_non_numeric_depot_id(self):
        text = (
            '"AppState"\n{\n"appid" "1"\n"InstalledDepots"\n{\n'
            '"not-a-depot"\n{\n"manifest" "1"\n}\n}\n}\n'
        )
        with self.assertRaises(AcfParseError):
            parse_acf(text)

    def test_invalid_manifest_gid(self):
        text = (
            '"AppState"\n{\n"appid" "1"\n"InstalledDepots"\n{\n'
            '"100"\n{\n"manifest" "gid-x"\n}\n}\n}\n'
        )
        with self.assertRaises(AcfParseError):
            parse_acf(text)

    def test_parse_from_path_records_source_path(self):
        state = parse_acf_file(L4D2)
        self.assertTrue(state.source_path.endswith("appmanifest_550.sample.acf"))


if __name__ == "__main__":
    unittest.main()
